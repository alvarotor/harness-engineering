// Package deploy tests infra/deploy/deploy.sh with a fake ssh on an isolated PATH. Real tar and ssh-keygen run.
package deploy

import (
	"archive/tar"
	"bytes"
	"errors"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

var script, _ = filepath.Abs("../../../../infra/deploy/deploy.sh")

// realTools are symlinked into the isolated PATH; the test skips when one is missing.
var realTools = []string{"sh", "tar", "ssh-keygen", "mktemp", "sed", "awk", "tr", "tail", "cp", "mkdir", "rm", "cat"}

const (
	host       = "deploy.example.com"
	user       = "deployer"
	secretVal  = "s3cr3t=value"
	secretAuth = "k2"
)

// fakeSSH logs each call's arguments, saves the bundle sent to `tar -xf -`, and reports healthy services for `ps`.
const fakeSSH = `#!/bin/sh
echo "ssh $*" >> "$FAKE_LOG"
case "$*" in
  *"tar -xf -"*) cat > "$FAKE_STDIN" ;;
  *"ps --all"*) echo 'demo|running|healthy|0' ;;
esac
`

// entry is one archive member: its permission bits and content.
type entry struct {
	mode    int64
	content string
}

type harness struct {
	t       *testing.T
	root    string // fake repository root the script runs in
	bin     string // isolated PATH
	log     string // one line per ssh call
	stdin   string // the bundle streamed to the remote tar
	known   string // DEPLOY_KNOWN_HOSTS file
	env     string
	secrets string
}

func newHarness(t *testing.T) *harness {
	t.Helper()
	for _, tool := range realTools {
		if _, err := exec.LookPath(tool); err != nil {
			t.Skipf("%s not available: %v", tool, err)
		}
	}
	dir := t.TempDir()
	h := &harness{
		t:       t,
		root:    filepath.Join(dir, "repo"),
		bin:     filepath.Join(dir, "bin"),
		log:     filepath.Join(dir, "calls.log"),
		stdin:   filepath.Join(dir, "bundle.tar"),
		known:   filepath.Join(dir, "known_hosts"),
		env:     filepath.Join(dir, "release.env"),
		secrets: filepath.Join(dir, "secrets.env"),
	}
	if err := os.MkdirAll(h.bin, 0o750); err != nil {
		t.Fatal(err)
	}
	for _, tool := range realTools {
		p, _ := exec.LookPath(tool)
		if err := os.Symlink(p, filepath.Join(h.bin, tool)); err != nil {
			t.Fatal(err)
		}
	}
	write(t, filepath.Join(h.bin, "ssh"), fakeSSH, 0o700)

	for rel, content := range map[string]string{
		"infra/compose/compose.yaml":        "services: {}\n",
		"infra/compose/compose.deploy.yaml": "services: {}\n",
		"infra/traefik/traefik.yml":         "entryPoints: {}\n",
		"infra/postgres/init.sql":           "-- init\n",
		"services/demo/compose.yaml":        "services: {}\n",
	} {
		write(t, filepath.Join(h.root, rel), content, 0o600)
	}
	write(t, h.env, "ENV=dev\nIMAGE_DEMO=ghcr.io/example/demo@sha256:abc\n", 0o600)
	write(t, h.secrets, "# runtime secrets\n\nPOSTGRES_PASSWORD="+secretVal+"\nAUTH_KEY="+secretAuth+"\n", 0o600)
	h.writeKnownHosts(host)
	return h
}

// writeKnownHosts pins a freshly generated ed25519 host key for the given host name.
func (h *harness) writeKnownHosts(name string) {
	h.t.Helper()
	key := filepath.Join(h.t.TempDir(), "hostkey")
	if out, err := exec.Command("ssh-keygen", "-q", "-t", "ed25519", "-N", "", "-f", key).CombinedOutput(); err != nil { //nolint:gosec // fixed tool, key path inside t.TempDir()
		h.t.Fatalf("ssh-keygen: %v\n%s", err, out)
	}
	pub, err := os.ReadFile(key + ".pub") //nolint:gosec // key generated by this test in t.TempDir()
	if err != nil {
		h.t.Fatal(err)
	}
	write(h.t, h.known, name+" "+string(pub), 0o600)
}

func write(t *testing.T, p, content string, mode os.FileMode) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), mode); err != nil { //nolint:gosec // fixture inside t.TempDir(); the fake ssh must be executable
		t.Fatal(err)
	}
}

// deploy runs deploy.sh with the given extra arguments after the environment name, host and user.
func (h *harness) deploy(args ...string) (string, int) {
	h.t.Helper()
	full := append([]string{script, "dev", host, user, h.env, h.secrets, h.known}, args...)
	cmd := exec.Command("/bin/sh", full...) //nolint:gosec // fixed script path under test
	cmd.Dir = h.root
	cmd.Env = []string{"PATH=" + h.bin, "FAKE_LOG=" + h.log, "FAKE_STDIN=" + h.stdin, "HOME=" + h.root}
	out, err := cmd.CombinedOutput()
	var exitErr *exec.ExitError
	if errors.As(err, &exitErr) {
		return string(out), exitErr.ExitCode()
	}
	if err != nil {
		h.t.Fatal(err)
	}
	return string(out), 0
}

// sshCalls returns the logged ssh invocations.
func (h *harness) sshCalls() []string {
	data, err := os.ReadFile(h.log)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		h.t.Fatal(err)
	}
	return strings.Split(strings.TrimSpace(string(data)), "\n")
}

// bundle returns the archive streamed to the remote, as name -> header and content.
func (h *harness) bundle() map[string]entry {
	h.t.Helper()
	f, err := os.Open(h.stdin) //nolint:gosec // bundle written by the fake ssh inside t.TempDir()
	if err != nil {
		h.t.Fatalf("no bundle was sent: %v", err)
	}
	defer func() { _ = f.Close() }()
	out := map[string]entry{}
	tr := tar.NewReader(f)
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			return out
		}
		if err != nil {
			h.t.Fatal(err)
		}
		var buf bytes.Buffer
		if _, err := io.Copy(&buf, tr); err != nil { //nolint:gosec // archive written by this test, not untrusted input
			h.t.Fatal(err)
		}
		out[strings.TrimSuffix(hdr.Name, "/")] = entry{hdr.Mode & 0o777, buf.String()}
	}
}

func TestDeploy_RefusesWithoutPinnedHostKey(t *testing.T) {
	cases := map[string]func(h *harness){
		"empty known_hosts": func(h *harness) { write(h.t, h.known, "", 0o600) },
		"host not pinned":   func(h *harness) { h.writeKnownHosts("other.example.com") },
		"known_hosts file missing": func(h *harness) {
			if err := os.Remove(h.known); err != nil {
				h.t.Fatal(err)
			}
		},
	}
	for name, mutate := range cases {
		t.Run(name, func(t *testing.T) {
			h := newHarness(t)
			mutate(h)
			out, code := h.deploy()
			if code == 0 {
				t.Fatalf("deploy must fail, output:\n%s", out)
			}
			if calls := h.sshCalls(); len(calls) != 0 {
				t.Errorf("ssh was called %d times before the host key check passed: %v", len(calls), calls)
			}
		})
	}
}

func TestDeploy_RejectsInvalidSecretsBeforeAnySSH(t *testing.T) {
	cases := map[string]string{
		"lowercase name": "postgres_password=x\n",
		"no equals sign": "POSTGRES_PASSWORD\n",
		"empty file":     "# nothing here\n",
	}
	for name, content := range cases {
		t.Run(name, func(t *testing.T) {
			h := newHarness(t)
			write(t, h.secrets, content, 0o600)
			if out, code := h.deploy(); code == 0 {
				t.Fatalf("deploy must fail, output:\n%s", out)
			}
			if calls := h.sshCalls(); len(calls) != 0 {
				t.Errorf("ssh was called before the secrets were validated: %v", calls)
			}
		})
	}
}

func TestDeploy_ValidInputsUseStrictHostKeyChecking(t *testing.T) {
	h := newHarness(t)
	out, code := h.deploy()
	if code != 0 {
		t.Fatalf("exit = %d, output:\n%s", code, out)
	}
	if !strings.Contains(out, "all services running and healthy") {
		t.Errorf("output missing the health result:\n%s", out)
	}

	calls := h.sshCalls()
	if len(calls) != 5 { // clean up, extract the bundle, pull, up, status
		t.Fatalf("ssh calls = %d, want 5: %v", len(calls), calls)
	}
	for _, c := range calls {
		for _, want := range []string{
			"-o StrictHostKeyChecking=yes",
			"-o UserKnownHostsFile=" + h.known,
			"-o GlobalKnownHostsFile=/dev/null",
			"-o BatchMode=yes",
			user + "@" + host,
		} {
			if !strings.Contains(c, want) {
				t.Errorf("ssh call lacks %q: %s", want, c)
			}
		}
		if strings.Contains(c, "StrictHostKeyChecking=no") || strings.Contains(c, "accept-new") {
			t.Errorf("ssh call relaxes host key checking: %s", c)
		}
	}
	if data, _ := os.ReadFile(h.log); bytes.Contains(data, []byte(secretVal)) || bytes.Contains(data, []byte(secretAuth)) {
		t.Error("a secret value reached the ssh command line")
	}
}

func TestDeploy_SSHKeyOptionIsPassedThrough(t *testing.T) {
	h := newHarness(t)
	key := filepath.Join(h.root, "deploy_key")
	write(t, key, "private", 0o600)
	if out, code := h.deploy(key); code != 0 {
		t.Fatalf("exit = %d, output:\n%s", code, out)
	}
	for _, c := range h.sshCalls() {
		if !strings.Contains(c, "-i "+key+" -o IdentitiesOnly=yes") {
			t.Errorf("ssh call does not use the key: %s", c)
		}
	}
}

func TestDeploy_StagesSecretsAsOwnerOnlyFiles(t *testing.T) {
	h := newHarness(t)
	if out, code := h.deploy(); code != 0 {
		t.Fatalf("exit = %d, output:\n%s", code, out)
	}
	b := h.bundle()

	for name, want := range map[string]string{
		"secrets/postgres_password": secretVal,
		"secrets/auth_key":          secretAuth,
	} {
		got, ok := b[name]
		if !ok {
			t.Errorf("bundle lacks %s", name)
			continue
		}
		if got.mode != 0o600 {
			t.Errorf("%s mode = %o, want 600", name, got.mode)
		}
		if got.content != want {
			t.Errorf("%s content = %q, want %q", name, got.content, want)
		}
	}
	if dir, ok := b["secrets"]; !ok || dir.mode != 0o700 {
		t.Errorf("secrets folder = %+v, want mode 700", dir)
	}

	envFile := b[".env"].content
	if !strings.Contains(envFile, "HAR_SECRETS_DIR=./secrets") || !strings.Contains(envFile, "ENV=dev") {
		t.Errorf(".env = %q, want release values and the secrets folder", envFile)
	}
	for _, leaked := range []string{secretVal, "POSTGRES_PASSWORD", "AUTH_KEY"} {
		if strings.Contains(envFile, leaked) {
			t.Errorf(".env must not carry secrets: found %q", leaked)
		}
	}
	for _, p := range []string{"infra/compose/compose.yaml", "infra/traefik/traefik.yml", "services/demo/compose.yaml"} {
		if _, ok := b[p]; !ok {
			t.Errorf("bundle lacks Compose input %s", p)
		}
	}
}
